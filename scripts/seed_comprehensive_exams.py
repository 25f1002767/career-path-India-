def seed_exams():
    with app.app_context():
        print(f"Starting synchronization of {len(REAL_EXAMINATIONS)} verified examination records...")
        
        updated_count = 0
        inserted_count = 0

        for exam_data in REAL_EXAMINATIONS:
            # Check for existing exam by name or short_name
            existing = GovernmentExam.query.filter(
                (GovernmentExam.exam_name == exam_data["exam_name"]) |
                (GovernmentExam.short_name == exam_data.get("short_name"))
            ).first()

            if existing:
                for k, v in exam_data.items():
                    setattr(existing, k, v)
                existing.last_verified_at = datetime.utcnow()
                existing.verification_status = "VERIFIED"
                updated_count += 1
            else:
                new_exam = GovernmentExam(**exam_data)
                new_exam.verification_status = "VERIFIED"
                new_exam.last_verified_at = datetime.utcnow()
                db.session.add(new_exam)
                inserted_count += 1

        db.session.commit()
        total_exams = GovernmentExam.query.count()
        print(f"Sync complete! Inserted: {inserted_count}, Updated: {updated_count}. Total Exams in DB: {total_exams}")

if __name__ == "__main__":
    seed_exams()
